// Package entcerbos reads a cerbosent.Schema from an ent schema graph, so a mapper names ent
// edges and columns and the adapter takes each edge's cardinality and joins from ent itself.
//
// Load builds the schema at runtime from the schema types; Extension writes it into the
// generated package as CerbosSchema, so the application does not link ent's code generator.
package entcerbos

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	"entgo.io/ent"
	"entgo.io/ent/entc"
	"entgo.io/ent/entc/gen"
	"entgo.io/ent/entc/load"

	cerbosent "github.com/cerbos/query-plan-adapters/ent"
)

// Load resolves the graph of the given schema types, as entc does, and reads it. Pass every
// type an edge reaches.
func Load(schemas ...ent.Interface) (*cerbosent.Schema, error) {
	loaded := make([]*load.Schema, 0, len(schemas))
	for _, s := range schemas {
		raw, err := load.MarshalSchema(s)
		if err != nil {
			return nil, err
		}
		var ls load.Schema
		if err := json.Unmarshal(raw, &ls); err != nil {
			return nil, err
		}
		loaded = append(loaded, &ls)
	}
	graph, err := gen.NewGraph(&gen.Config{}, loaded...)
	if err != nil {
		return nil, err
	}
	return FromGraph(graph)
}

// FromGraph reads a resolved ent graph.
func FromGraph(graph *gen.Graph) (*cerbosent.Schema, error) {
	schema := &cerbosent.Schema{}
	nodes := slices.SortedFunc(slices.Values(graph.Nodes), func(a, b *gen.Type) int { return strings.Compare(a.Name, b.Name) })
	for _, t := range nodes {
		st := cerbosent.SchemaType{Name: t.Name, Table: t.Table(), Columns: map[string]string{}}
		if t.HasOneFieldID() {
			st.ID = t.ID.StorageKey()
			st.Columns[st.ID] = t.ID.Type.Type.String()
		}
		for _, f := range t.Fields {
			st.Columns[f.StorageKey()] = f.Type.Type.String()
		}
		for _, e := range t.Edges {
			edge, err := readEdge(t, e)
			if err != nil {
				return nil, err
			}
			st.Edges = append(st.Edges, edge)
		}
		schema.Types = append(schema.Types, st)
	}
	return schema, nil
}

func readEdge(owner *gen.Type, e *gen.Edge) (cerbosent.SchemaEdge, error) {
	edge := cerbosent.SchemaEdge{Name: e.Name, Type: e.Type.Name, Unique: e.Unique}
	if e.Rel.Type == gen.M2M {
		if !owner.HasOneFieldID() || !e.Type.HasOneFieldID() || len(e.Rel.Columns) != 2 {
			return edge, nil
		}
		own, other := e.Rel.Columns[0], e.Rel.Columns[1]
		if e.IsInverse() {
			own, other = other, own
		}
		edge.Join = []cerbosent.SchemaJoin{
			{Table: e.Rel.Table, FromColumn: owner.ID.StorageKey(), ToColumn: own},
			{Table: e.Type.Table(), FromColumn: other, ToColumn: e.Type.ID.StorageKey()},
		}
		return edge, nil
	}
	if len(e.Rel.Columns) != 1 || !owner.HasOneFieldID() || !e.Type.HasOneFieldID() {
		return edge, nil
	}
	fk := e.Rel.Columns[0]
	switch {
	case e.OwnFK():
		edge.Join = []cerbosent.SchemaJoin{{Table: e.Type.Table(), FromColumn: fk, ToColumn: e.Type.ID.StorageKey()}}
	case e.Rel.Type == gen.O2M || e.Rel.Type == gen.O2O:
		edge.Join = []cerbosent.SchemaJoin{{Table: e.Type.Table(), FromColumn: owner.ID.StorageKey(), ToColumn: fk}}
	default:
		return edge, fmt.Errorf("entcerbos: edge %s.%s has relation %s", owner.Name, e.Name, e.Rel.Type)
	}
	return edge, nil
}

const generatedFileMode = 0o600

// Extension writes cerbos_schema.go, declaring CerbosSchema, into the generated package.
//
//	entc.Generate("./schema", &gen.Config{}, entc.Extensions(entcerbos.Extension{}))
type Extension struct {
	entc.DefaultExtension
}

// Hooks of the extension.
func (Extension) Hooks() []gen.Hook {
	return []gen.Hook{func(next gen.Generator) gen.Generator {
		return gen.GenerateFunc(func(g *gen.Graph) error {
			if err := next.Generate(g); err != nil {
				return err
			}
			schema, err := FromGraph(g)
			if err != nil {
				return err
			}
			src, err := Source(path.Base(g.Package), schema)
			if err != nil {
				return err
			}
			return os.WriteFile(filepath.Join(g.Target, "cerbos_schema.go"), src, generatedFileMode)
		})
	}}
}

// Source renders schema as a Go file in package pkg declaring CerbosSchema.
func Source(pkg string, schema *cerbosent.Schema) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by entcerbos, DO NOT EDIT.\n\npackage %s\n\n", pkg)
	b.WriteString("import cerbosent \"github.com/cerbos/query-plan-adapters/ent\"\n\n")
	b.WriteString("// CerbosSchema is this graph's tables, columns and edges, for cerbosent.Schema.Mapper.\n")
	b.WriteString("var CerbosSchema = &cerbosent.Schema{Types: []cerbosent.SchemaType{\n")
	for _, t := range schema.Types {
		fmt.Fprintf(&b, "{Name: %q, Table: %q, ID: %q, Columns: map[string]string{", t.Name, t.Table, t.ID)
		cols := make([]string, 0, len(t.Columns))
		for c := range t.Columns {
			cols = append(cols, c)
		}
		sort.Strings(cols)
		for _, c := range cols {
			fmt.Fprintf(&b, "%q: %q,", c, t.Columns[c])
		}
		b.WriteString("}")
		if len(t.Edges) > 0 {
			b.WriteString(", Edges: []cerbosent.SchemaEdge{\n")
		}
		for _, e := range t.Edges {
			fmt.Fprintf(&b, "{Name: %q, Type: %q, Unique: %t, Join: []cerbosent.SchemaJoin{", e.Name, e.Type, e.Unique)
			for _, j := range e.Join {
				fmt.Fprintf(&b, "{Table: %q, FromColumn: %q, ToColumn: %q},", j.Table, j.FromColumn, j.ToColumn)
			}
			b.WriteString("}},\n")
		}
		if len(t.Edges) > 0 {
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}}\n")
	return format.Source(b.Bytes())
}
