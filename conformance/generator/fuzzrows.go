// fuzz -rows N adds N generated rows to the dataset a fuzz run is recorded against. The fuzzer
// varies conditions; these vary the data: each row recombines values the hand-written seeds already
// hold for each attribute (so every store that holds the seeds can hold it) with a few boundary
// values no seed holds. The run's seeds.json, derived-fields.json and resources.json are written into
// the fuzz directory, and a harness replaying it loads them in place of the corpus dataset.

// datasetFiles are the dataset files a fuzz directory carries when its rows differ from the corpus.
var datasetFiles = []string{"seeds.json", "derived-fields.json", "resources.json"}

// rowExtras are boundary values no hand-written seed holds, by attribute.
var rowExtras = map[string][]any{
	"aString":         {"ONE", " one", "one ", "ß", "SS", "İ", "i", "é", "%", "_", "'", "\"", "a%b", "1.5", "-1"},
	"aOptionalString": {"SET", "set ", "%", "_"},
	"aNumber":         {json.Number("-1"), json.Number("50"), json.Number("51"), json.Number("2147483647"), json.Number("-2147483648")},
	"aDouble":         {json.Number("0.5"), json.Number("-0.5"), json.Number("2.5"), json.Number("0.1"), json.Number("1e-7"), json.Number("5"), json.Number("-1")},
	"createdAt":       {"1999-12-31T23:59:59.999Z", "2024-02-29T00:00:00Z", "2001-01-01T00:00:00.5Z"},
	"listElement":     {json.Number("-1"), json.Number("5"), json.Number("50")},
}

// rowExcluded are values a hand-written seed holds on purpose that generated rows must not copy:
// a known mapping hazard would fail every case that reads the attribute.
var rowExcluded = map[string]map[string]bool{
	// Sub-millisecond on millisecond stores (README.md, "Mapping hazards").
	"createdAt": {`"2020-03-15T10:30:00.123456Z"`: true},
}

func generateRows(conf string, seed uint64, n int) (map[string][]byte, error) {
	var seedsFile map[string]any
	if err := decodeJSONFile(filepath.Join(conf, "seeds.json"), &seedsFile); err != nil {
		return nil, err
	}
	var derivedFile map[string]any
	if err := decodeJSONFile(filepath.Join(conf, "derived-fields.json"), &derivedFile); err != nil {
		return nil, err
	}
	seeds := seedsFile["seeds"].([]any)
	derived := derivedFile["derived"].(map[string]any)

	ids := map[string]bool{}
	var parents []string
	pal := newPalettes()
	for _, s := range seeds {
		row := s.(map[string]any)
		id := row["id"].(string)
		ids[id] = true
		if relatable(row) {
			parents = append(parents, id)
		}
		for _, k := range []string{"aBool", "aString", "aNumber", "aOptionalString", "aNumberList", "aBoolList", "subCategoryNames"} {
			pal.add(k, row[k])
		}
		for _, el := range listOf(row["aNumberList"]) {
			pal.add("listElement", el)
		}
		for _, el := range listOf(row["aBoolList"]) {
			pal.add("boolElement", el)
		}
		for _, t := range listOf(row["tags"]) {
			pal.add("tagName", t.(map[string]any)["name"])
		}
		for k, v := range derived[id].(map[string]any) {
			pal.add(k, v)
		}
	}
	for k, vs := range rowExtras {
		for _, v := range vs {
			pal.add(k, v)
		}
	}

	rng := rand.New(rand.NewPCG(seed, 0x5851f42d4c957f2d))
	pick := func(k string) any { return pal.pick(rng, k) }
	maybe := func(p float64) bool { return rng.Float64() < p }
	for i := range n {
		id := fmt.Sprintf("g%03d", i)
		if ids[id] {
			return nil, fmt.Errorf("fuzz -rows: generated id %q is a seed id", id)
		}
		row := map[string]any{
			"id":               id,
			"aBool":            pick("aBool"),
			"aString":          pick("aString"),
			"aNumber":          pick("aNumber"),
			"aOptionalString":  pick("aOptionalString"),
			"aNumberList":      pick("aNumberList"),
			"aBoolList":        pick("aBoolList"),
			"subCategoryNames": pick("subCategoryNames"),
			"parentSeedId":     nil,
			"note":             fmt.Sprintf("Generated by fuzz -seed %d -rows %d.", seed, n),
		}
		if maybe(0.5) {
			row["aNumberList"] = drawList(rng, pal, "listElement")
		}
		if maybe(0.5) {
			row["aBoolList"] = drawList(rng, pal, "boolElement")
		}
		tags := []any{}
		for t := range rng.IntN(4) {
			tags = append(tags, map[string]any{"id": fmt.Sprintf("%st%d", id, t), "name": pick("tagName")})
		}
		row["tags"] = tags
		if maybe(0.7) {
			row["parentSeedId"] = parents[rng.IntN(len(parents))]
		}
		if maybe(0.3) {
			row["peerSeedId"] = parents[rng.IntN(len(parents))]
		}
		if maybe(0.3) {
			row["stepParentSeedId"] = parents[rng.IntN(len(parents))]
		}
		var requires []any
		if s, _ := row["aString"].(string); strings.ContainsRune(s, 0) {
			requires = append(requires, "nul-in-string")
		}
		if row["aNumberList"] == nil {
			requires = append(requires, "null-list")
		}
		if requires != nil {
			row[requiresKey] = requires
		}
		if relatable(row) {
			parents = append(parents, id)
		}
		d := map[string]any{}
		for _, k := range derivedKeys {
			d[k] = pick(k)
		}
		seeds = append(seeds, row)
		derived[id] = d
	}
	seedsFile["seeds"] = seeds
	derivedFile["derived"] = derived

	files := map[string][]byte{}
	var err error
	if files["seeds.json"], err = marshalJSON(seedsFile); err != nil {
		return nil, err
	}
	if files["derived-fields.json"], err = marshalJSON(derivedFile); err != nil {
		return nil, err
	}
	ds, err := loadDatasetFiles(files)
	if err != nil {
		return nil, fmt.Errorf("fuzz -rows: the generated dataset: %w", err)
	}
	if files["resources.json"], err = buildResourcesJSON(ds); err != nil {
		return nil, err
	}
	return files, nil
}

// loadDatasetFiles loads a dataset held in memory, through the same checks as the corpus.
func loadDatasetFiles(files map[string][]byte) (*Dataset, error) {
	dir, err := os.MkdirTemp("", "fuzz-rows-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(dir)
	for _, name := range []string{"seeds.json", "derived-fields.json"} {
		if err := os.WriteFile(filepath.Join(dir, name), files[name], 0o644); err != nil {
			return nil, err
		}
	}
	return loadDataset(dir)
}

// useFuzzDataset switches the inputs to the dataset a fuzz directory carries, if it carries one.
func (in *fuzzInputs) useFuzzDataset(dir string) error {
	if _, err := os.Stat(filepath.Join(dir, "seeds.json")); err != nil {
		return nil
	}
	files := map[string][]byte{}
	for _, name := range datasetFiles {
		raw, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return err
		}
		files[name] = raw
	}
	ds, err := loadDataset(dir)
	if err != nil {
		return err
	}
	in.ds, in.dataset = ds, files
	return nil
}

// relatable reports whether a row may be another row's parent, peer or step-parent. Every
// hand-written one holds aBool, aString and aNumber, and harness schemas declare those columns NOT
// NULL on the related tables.
func relatable(row map[string]any) bool {
	return row[requiresKey] == nil && row["aBool"] != nil && row["aString"] != nil && row["aNumber"] != nil
}

func listOf(v any) []any {
	l, _ := v.([]any)
	return l
}

func drawList(rng *rand.Rand, pal *palettes, key string) []any {
	out := []any{}
	for range rng.IntN(4) {
		out = append(out, pal.pick(rng, key))
	}
	return out
}

// palettes are the distinct values seen per attribute, in a stable order.
type palettes struct {
	seen   map[string]map[string]bool
	values map[string][]any
}

func newPalettes() *palettes {
	return &palettes{seen: map[string]map[string]bool{}, values: map[string][]any{}}
}

func (p *palettes) add(key string, v any) {
	raw, err := json.Marshal(v)
	if err != nil {
		panic(err)
	}
	k := string(raw)
	if rowExcluded[key][k] {
		return
	}
	if p.seen[key] == nil {
		p.seen[key] = map[string]bool{}
	}
	if p.seen[key][k] {
		return
	}
	p.seen[key][k] = true
	p.values[key] = append(p.values[key], v)
}

func (p *palettes) pick(rng *rand.Rand, key string) any {
	vs := p.values[key]
	if len(vs) == 0 {
		panic("fuzz -rows: no values for " + key)
	}
	sorted := make([]any, len(vs))
	copy(sorted, vs)
	sort.SliceStable(sorted, func(i, j int) bool {
		a, _ := json.Marshal(sorted[i])
		b, _ := json.Marshal(sorted[j])
		return bytes.Compare(a, b) < 0
	})
	return deepCopyJSON(sorted[rng.IntN(len(sorted))])
}
