// A fuzz case is one action whose condition the fuzzer composed, not a hand-written case: an ALLOW
// rule over one condition tree and, sometimes, a DENY rule over a second. The tree is kept beside
// the rendered CEL so fuzz-shrink can take it apart again.

// fnode is one node of a generated condition. Op is "atom" (CEL is the whole expression), "and",
// "or", "not" or "cond" (Kids are the ternary's condition, then and else).
type fnode struct {
	Op   string   `json:"op"`
	CEL  string   `json:"cel,omitempty"`
	From string   `json:"from,omitempty"`
	Kids []*fnode `json:"kids,omitempty"`
}

// fuzzCase is one generated action.
type fuzzCase struct {
	ID    string `json:"id"`
	Allow *fnode `json:"allow"`
	Deny  *fnode `json:"deny,omitempty"`
}

func (n *fnode) render() string {
	switch n.Op {
	case "atom":
		return n.CEL
	case "not":
		return "!(" + n.Kids[0].render() + ")"
	case "and", "or":
		sep := " && "
		if n.Op == "or" {
			sep = " || "
		}
		parts := make([]string, len(n.Kids))
		for i, k := range n.Kids {
			parts[i] = "(" + k.render() + ")"
		}
		return strings.Join(parts, sep)
	case "cond":
		return "(" + n.Kids[0].render() + ") ? (" + n.Kids[1].render() + ") : (" + n.Kids[2].render() + ")"
	}
	panic("fuzz: unknown node op " + n.Op)
}

func (n *fnode) size() int {
	s := 1
	for _, k := range n.Kids {
		s += k.size()
	}
	return s
}

func (fc *fuzzCase) size() int {
	s := fc.Allow.size()
	if fc.Deny != nil {
		s += fc.Deny.size()
	}
	return s
}

func (n *fnode) clone() *fnode {
	c := &fnode{Op: n.Op, CEL: n.CEL, From: n.From}
	for _, k := range n.Kids {
		c.Kids = append(c.Kids, k.clone())
	}
	return c
}

// asCase is the case the policy builder and recorder take: one ALLOW rule for USER, plus the DENY
// rule when there is one.
func (fc *fuzzCase) asCase(seed uint64) *Case {
	c := &Case{
		ID:     fc.ID,
		Tier:   "adversarial",
		Intent: fc.describe(),
		Trap:   fmt.Sprintf("Generated by fuzz -seed %d: a translation that returns rows the PDP denies, or misses rows it allows, without refusing.", seed),
		area:   "fuzz",
	}
	c.Rules = []map[string]any{{
		"effect":    "EFFECT_ALLOW",
		"roles":     []any{"USER"},
		"condition": map[string]any{"match": map[string]any{"expr": fc.Allow.render()}},
	}}
	if fc.Deny != nil {
		c.Rules = append(c.Rules, map[string]any{
			"effect":    "EFFECT_DENY",
			"roles":     []any{"USER"},
			"condition": map[string]any{"match": map[string]any{"expr": fc.Deny.render()}},
		})
	}
	return c
}

func (fc *fuzzCase) describe() string {
	if fc.Deny == nil {
		return "ALLOW " + fc.Allow.render()
	}
	return "ALLOW " + fc.Allow.render() + " unless DENY " + fc.Deny.render()
}

// corpusAtom is one hand-written expression the fuzzer composes.
type corpusAtom struct {
	ID  string
	CEL string
}

// corpusAtoms collects every single expression the hand-written cases hold, from a bare match.expr
// or from one level of match.all/any/none. Cases the planner and check() disagree on are left out,
// since a composition over one would fail every adapter for the planner's reason; so are
// expressions over now(), whose recorded value is a placeholder.
func corpusAtoms(corpus *Corpus) []corpusAtom {
	var atoms []corpusAtom
	add := func(id string, expr any) {
		s, ok := expr.(string)
		if !ok || strings.Contains(s, "now()") || strings.Contains(s, "timeSince") {
			return
		}
		atoms = append(atoms, corpusAtom{ID: id, CEL: s})
	}
	for _, c := range corpus.Cases {
		if c.PlannerDivergence != nil || c.Condition == nil {
			continue
		}
		cond, _ := c.Condition.(map[string]any)
		match, _ := cond["match"].(map[string]any)
		if match == nil {
			continue
		}
		if e, ok := match["expr"]; ok {
			add(c.ID, e)
			continue
		}
		for _, k := range []string{"all", "any", "none"} {
			group, _ := match[k].(map[string]any)
			of, _ := group["of"].([]any)
			for _, item := range of {
				if m, ok := item.(map[string]any); ok {
					add(c.ID, m["expr"])
				}
			}
		}
	}
	return atoms
}

// fuzzer draws conditions from a seeded generator, so one seed always yields the same cases.
type fuzzer struct {
	rng   *rand.Rand
	atoms []corpusAtom
	pools map[string][]any
}

func newFuzzer(seed uint64, corpus *Corpus, ds *Dataset) *fuzzer {
	return &fuzzer{
		rng:   rand.New(rand.NewPCG(seed, 0x9e3779b97f4a7c15)),
		atoms: corpusAtoms(corpus),
		pools: valuePools(ds),
	}
}

// valuePools lists, for each attribute path (dotted, under R.attr, plus "id"), the distinct scalar
// values the dataset holds there, and for a list path the distinct elements. Literals drawn from
// these discriminate between seeds; a literal drawn from nowhere usually matches no row.
func valuePools(ds *Dataset) map[string][]any {
	seen := map[string]map[string]any{}
	put := func(path string, v any) {
		if v == nil {
			return
		}
		if seen[path] == nil {
			seen[path] = map[string]any{}
		}
		seen[path][fmt.Sprintf("%T:%v", v, v)] = v
	}
	var walk func(prefix string, v any)
	walk = func(prefix string, v any) {
		switch t := v.(type) {
		case map[string]any:
			for k, inner := range t {
				walk(prefix+"."+k, inner)
			}
		case []any:
			for _, e := range t {
				if m, ok := e.(map[string]any); ok {
					for k, inner := range m {
						walk(prefix+"[]."+k, inner)
					}
					continue
				}
				put(prefix+"[]", e)
			}
		default:
			put(prefix, v)
		}
	}
	for _, r := range ds.Resources {
		put("id", r.ID)
		for k, v := range r.Attr {
			walk(k, v)
		}
	}
	pools := map[string][]any{}
	for path, vals := range seen {
		keys := make([]string, 0, len(vals))
		for k := range vals {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			pools[path] = append(pools[path], vals[k])
		}
	}
	return pools
}

// The attributes the grammar reads, by type, as the policy spells them. Every one is read by some
// hand-written case, so every harness's mapping covers it: an attribute only the fuzzer reads would
// fail on a mapping gap in the harness rather than on the adapter.
var (
	fuzzStrings = []string{
		"R.attr.aString", "R.attr.aOptionalString", "R.attr.owner", "R.attr.coOwner", "R.attr.scope",
		"R.attr.obj.inner", "R.attr.parent.aString", "R.attr.parent.aOptionalString",
		"R.attr.parent.inner.aString", "R.id",
	}
	fuzzInts      = []string{"R.attr.aNumber", "R.attr.parent.aNumber"}
	fuzzDoubles   = []string{"R.attr.aDouble"}
	fuzzBools     = []string{"R.attr.aBool", "R.attr.parent.aBool", "R.attr.parent.inner.aBool"}
	fuzzStrLists  = []string{"R.attr.tagNames", "R.attr.mainCategory.subNames"} // hasIntersection only
	fuzzTimes     = []string{"R.attr.createdAt", "R.attr.updatedAt", "R.attr.createdBy"}
	fuzzPStrings  = []string{"P.attr.context"}
	fuzzPStrLists = []string{"P.attr.allowedTags", "P.attr.fewTeams", "P.attr.manyTeams", "P.attr.emptyTeams", "P.attr.duplicateTeams"}
	// fuzzFixedPaths are the attributes the list and struct-list atoms spell out in full.
	fuzzFixedPaths = []string{"R.attr.aNumberList", "R.attr.aBoolList", "R.attr.tags", "R.attr.categories", "P.attr.zero"}
	fuzzRegexes    = []string{"^on", "e$", "^.{3}$", "[0-9]", "^(one|two)$", "x{2,}", "(?i)^ONE$", "^$", "\\.", "^h.llo", "%", "^[a-z]+$", "\\d{2}"}
	fuzzOrderings  = []string{"==", "!=", "<", "<=", ">", ">="}
	fuzzEqs        = []string{"==", "!="}
)

// unreadGrammarPaths lists the grammar's attributes that no hand-written case reads any more, so
// the fuzzer stops before replaying a mapping gap as an adapter bug. A path counts only as a whole
// path: R.attr.aNumberList does not read R.attr.aNumber.
func unreadGrammarPaths(corpus *Corpus) []string {
	var text strings.Builder
	for _, c := range corpus.Cases {
		fmt.Fprintf(&text, "%v\n%v\n", c.Condition, c.Rules)
	}
	all := text.String()
	var missing []string
	for _, group := range [][]string{fuzzStrings, fuzzInts, fuzzDoubles, fuzzBools, fuzzStrLists, fuzzTimes, fuzzPStrings, fuzzPStrLists, fuzzFixedPaths} {
		for _, p := range group {
			if !regexp.MustCompile(regexp.QuoteMeta(p) + `\b`).MatchString(all) {
				missing = append(missing, p)
			}
		}
	}
	return missing
}

// poolPath is the valuePools key for a policy path: R.attr.parent.aString -> parent.aString.
func poolPath(p string) string {
	if p == "R.id" {
		return "id"
	}
	return strings.TrimPrefix(p, "R.attr.")
}

func (f *fuzzer) pick(xs []string) string { return xs[f.rng.IntN(len(xs))] }

func (f *fuzzer) chance(p float64) bool { return f.rng.Float64() < p }

// celString quotes s as a CEL string literal, escaping only what CEL requires.
func celString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// strLit draws a string literal: usually a value the dataset holds at path (or a piece of one),
// sometimes a boundary value no seed holds.
func (f *fuzzer) strLit(path string) string {
	pool := f.pools[poolPath(path)]
	var strs []string
	for _, v := range pool {
		if s, ok := v.(string); ok {
			strs = append(strs, s)
		}
	}
	boundary := []string{"", "%", "_", "100%", "a_b", "\\", "ONE", "one ", "é", "x", "public", "set", "dept"}
	if len(strs) == 0 || f.chance(0.2) {
		return celString(f.pick(boundary))
	}
	s := f.pick(strs)
	r := []rune(s)
	switch f.rng.IntN(6) {
	case 0:
		if len(r) > 1 {
			s = string(r[:1+f.rng.IntN(len(r)-1)])
		}
	case 1:
		if len(r) > 1 {
			s = string(r[f.rng.IntN(len(r)-1)+1:])
		}
	case 2:
		s = strings.ToUpper(s)
	}
	return celString(s)
}

// numLit draws a numeric literal, int or double, near the values the dataset holds at path.
func (f *fuzzer) numLit(path string, double bool) string {
	var nums []float64
	for _, v := range f.pools[poolPath(path)] {
		switch n := v.(type) {
		case float64:
			nums = append(nums, n)
		case int64:
			nums = append(nums, float64(n))
		case interface{ Float64() (float64, error) }:
			if x, err := n.Float64(); err == nil {
				nums = append(nums, x)
			}
		}
	}
	base := 0.0
	if len(nums) > 0 && !f.chance(0.15) {
		base = nums[f.rng.IntN(len(nums))]
	}
	switch f.rng.IntN(5) {
	case 0:
		base++
	case 1:
		base--
	}
	if double || f.chance(0.2) {
		if base == 0 && f.chance(0.3) {
			return "-0.0"
		}
		if base == float64(int64(base)) {
			return strconv.FormatFloat(base, 'f', 1, 64)
		}
		return strconv.FormatFloat(base, 'g', -1, 64)
	}
	return strconv.FormatInt(int64(base), 10)
}

// atom draws one leaf: a hand-written expression from the corpus, or a fresh one from the grammar.
func (f *fuzzer) atom() *fnode {
	if len(f.atoms) > 0 && f.chance(0.45) {
		a := f.atoms[f.rng.IntN(len(f.atoms))]
		return &fnode{Op: "atom", CEL: a.CEL, From: a.ID}
	}
	return &fnode{Op: "atom", CEL: f.grammarAtom()}
}

func (f *fuzzer) grammarAtom() string {
	switch f.rng.IntN(9) {
	case 0, 1:
		return f.stringAtom()
	case 2:
		return f.numberAtom()
	case 3:
		return f.boolAtom()
	case 4, 5:
		return f.listAtom()
	case 6:
		return f.structListAtom()
	case 7:
		return f.nullAtom()
	default:
		return f.timeAtom()
	}
}

func (f *fuzzer) stringAtom() string {
	s := f.pick(fuzzStrings)
	switch f.rng.IntN(12) {
	case 0:
		return fmt.Sprintf("%s %s %s", s, f.pick(fuzzEqs), f.strLit(s))
	case 1:
		return fmt.Sprintf("%s.startsWith(%s)", s, f.strLit(s))
	case 2:
		return fmt.Sprintf("%s.endsWith(%s)", s, f.strLit(s))
	case 3:
		return fmt.Sprintf("%s.contains(%s)", s, f.strLit(s))
	case 4:
		return fmt.Sprintf("%s in [%s, %s]", s, f.strLit(s), f.strLit(s))
	case 5:
		return fmt.Sprintf("%s %s %s", s, f.pick(fuzzOrderings[2:]), f.strLit(s))
	case 6:
		return fmt.Sprintf("size(%s) %s %d", s, f.pick(fuzzOrderings), f.rng.IntN(6))
	case 7:
		return fmt.Sprintf("%s.matches(%s)", s, celString(f.pick(fuzzRegexes)))
	case 8:
		return fmt.Sprintf("%s %s %s", s, f.pick(fuzzEqs), f.pick(fuzzStrings))
	case 9:
		return fmt.Sprintf("%s %s %s", s, f.pick(fuzzEqs), f.pick(fuzzPStrings))
	case 10:
		return fmt.Sprintf("%s in %s", s, f.pick(fuzzPStrLists))
	default:
		return fmt.Sprintf("%s.lowerAscii() == %s", s, f.strLit(s))
	}
}

func (f *fuzzer) numberAtom() string {
	n := f.pick(append(append([]string{}, fuzzInts...), fuzzDoubles...))
	double := n == "R.attr.aDouble"
	switch f.rng.IntN(7) {
	case 0, 1:
		return fmt.Sprintf("%s %s %s", n, f.pick(fuzzOrderings), f.numLit(n, double))
	case 2:
		// The operand is always a double literal: every numeric attribute reaches CEL as a double,
		// which has no double + int overload, and the planner drops an int literal's type, so an
		// int operand only rediscovers that planner divergence (#544) on every leg.
		op := f.pick([]string{"+", "-", "*"})
		return fmt.Sprintf("%s %s %s %s %s", n, op, f.numLit(n, true), f.pick(fuzzOrderings), f.numLit(n, double))
	case 3:
		if double {
			return fmt.Sprintf("%s / 2.0 %s %s", n, f.pick(fuzzOrderings), f.numLit(n, true))
		}
		return fmt.Sprintf("%s %% %d %s %d", n, 2+f.rng.IntN(3), f.pick(fuzzEqs), f.rng.IntN(2))
	case 4:
		return fmt.Sprintf("%s in [%s, %s]", n, f.numLit(n, double), f.numLit(n, double))
	case 5:
		return fmt.Sprintf("%s %s %s", n, f.pick(fuzzOrderings), f.pick(append(append([]string{"P.attr.zero"}, fuzzInts...), fuzzDoubles...)))
	default:
		if double {
			return fmt.Sprintf("int(%s) %s %s", n, f.pick(fuzzOrderings), f.numLit(n, false))
		}
		return fmt.Sprintf("double(%s) %s %s", n, f.pick(fuzzOrderings), f.numLit(n, true))
	}
}

func (f *fuzzer) boolAtom() string {
	b := f.pick(fuzzBools)
	switch f.rng.IntN(4) {
	case 0:
		return b
	case 1:
		return "!" + b
	case 2:
		return fmt.Sprintf("%s %s %v", b, f.pick(fuzzEqs), f.chance(0.5))
	default:
		return fmt.Sprintf("%s %s %s", b, f.pick(fuzzEqs), f.pick(fuzzBools))
	}
}

// listAtom reads a list attribute in the shapes the hand-written cases do, with the lambda
// variables they bind (t): a harness maps a lambda variable by name, so a fresh name, or a macro over
// a list no case iterates, fails on the harness's mapping rather than on the adapter.
func (f *fuzzer) listAtom() string {
	switch f.rng.IntN(5) {
	case 0:
		return fmt.Sprintf("%s in R.attr.aNumberList", f.numLit("aNumberList[]", false))
	case 1:
		return fmt.Sprintf("R.attr.aBoolList[0] %s %v", f.pick(fuzzEqs), f.chance(0.5))
	case 2:
		return fmt.Sprintf("hasIntersection(%s, %s)", f.pick(fuzzStrLists), f.pick(fuzzPStrLists))
	case 3:
		s := f.pick([]string{"R.attr.aOptionalString", "R.attr.owner", "R.attr.aString"})
		return f.pick([]string{
			fmt.Sprintf("%s.exists(t, %s == t)", f.pick(fuzzPStrLists), s),
			fmt.Sprintf("%s.all(t, %s != t)", f.pick(fuzzPStrLists), s),
			fmt.Sprintf("%s.exists_one(t, t == %s)", f.pick(fuzzPStrLists), s),
		})
	}
	l := "R.attr.tagNames"
	switch f.rng.IntN(5) {
	case 0:
		return fmt.Sprintf("%s in %s", f.strLit("tagNames[]"), l)
	case 1:
		return fmt.Sprintf("%s.exists(t, t.startsWith(%s))", l, f.strLit("tagNames[]"))
	case 2:
		return fmt.Sprintf("%s.all(t, t != %s)", l, f.strLit("tagNames[]"))
	case 3:
		return fmt.Sprintf("%s.filter(t, t != %s).size() %s %d", l, f.strLit("tagNames[]"), f.pick(fuzzOrderings), f.rng.IntN(3))
	default:
		return fmt.Sprintf("%s.exists(t, t == %s)", l, f.strLit("tagNames[]"))
	}
}

func (f *fuzzer) structListAtom() string {
	switch f.rng.IntN(7) {
	case 0:
		return fmt.Sprintf("R.attr.tags.exists(t, t.name == %s)", f.strLit("tags[].name"))
	case 1:
		return fmt.Sprintf("R.attr.tags.all(t, t.name != %s)", f.strLit("tags[].name"))
	case 2:
		return fmt.Sprintf("R.attr.tags.exists(t, t.name.startsWith(%s) && t.id != %s)", f.strLit("tags[].name"), f.strLit("tags[].id"))
	case 3:
		return fmt.Sprintf("R.attr.tags.exists_one(t, t.name == %s)", f.strLit("tags[].name"))
	case 4:
		return fmt.Sprintf("R.attr.tags.exists(t, t.name in %s)", f.pick(fuzzPStrLists))
	case 5:
		return fmt.Sprintf("R.attr.categories.exists(c, c.subCategories.exists(s, s.name == %s))", f.strLit("categories[].subCategories[].name"))
	default:
		return fmt.Sprintf("R.attr.tags.exists(t, has(t.name) && t.name %s %s)", f.pick(fuzzEqs), f.strLit("tags[].name"))
	}
}

func (f *fuzzer) nullAtom() string {
	// R.id is always present, so has() and null say nothing about it.
	var all []string
	for _, s := range fuzzStrings {
		if s != "R.id" {
			all = append(all, s)
		}
	}
	all = append(append(all, fuzzInts...), fuzzBools...)
	a := f.pick(all)
	switch f.rng.IntN(3) {
	case 0:
		return fmt.Sprintf("%s %s null", a, f.pick(fuzzEqs))
	case 1:
		return fmt.Sprintf("has(%s)", a)
	default:
		return fmt.Sprintf("!has(%s)", a)
	}
}

func (f *fuzzer) timeAtom() string {
	t := f.pick(fuzzTimes)
	lits := []string{"2020-03-15T10:30:00Z", "2024-06-01T00:00:00Z", "2030-01-01T00:00:00Z", "2000-01-01T00:00:00Z", "2020-03-15T10:30:00.001Z"}
	for _, v := range f.pools[poolPath(t)] {
		// A seed may hold a string that is not a timestamp (the type-mismatch rows); as a literal it
		// would stop the policy compiling.
		if s, ok := v.(string); ok {
			if _, err := time.Parse(time.RFC3339Nano, s); err == nil {
				lits = append(lits, s)
			}
		}
	}
	if f.chance(0.25) {
		return fmt.Sprintf("timestamp(%s).getFullYear() %s %d", t, f.pick(fuzzOrderings), 2018+f.rng.IntN(20))
	}
	return fmt.Sprintf("timestamp(%s) %s timestamp(%s)", t, f.pick(fuzzOrderings), celString(f.pick(lits)))
}

// tree draws a condition of at most depth levels of and/or/not/ternary above its leaves.
func (f *fuzzer) tree(depth int) *fnode {
	if depth == 0 || f.chance(0.3) {
		return f.atom()
	}
	switch r := f.rng.IntN(10); {
	case r < 4:
		n := &fnode{Op: "and"}
		for range 2 + f.rng.IntN(2) {
			n.Kids = append(n.Kids, f.tree(depth-1))
		}
		return n
	case r < 7:
		n := &fnode{Op: "or"}
		for range 2 + f.rng.IntN(2) {
			n.Kids = append(n.Kids, f.tree(depth-1))
		}
		return n
	case r < 9:
		return &fnode{Op: "not", Kids: []*fnode{f.tree(depth - 1)}}
	default:
		return &fnode{Op: "cond", Kids: []*fnode{f.tree(depth - 1), f.tree(depth - 1), f.tree(depth - 1)}}
	}
}

// fuzzCases draws count cases named fuzz/s<seed>/<index>.
func (f *fuzzer) fuzzCases(seed uint64, count int) []*fuzzCase {
	cases := make([]*fuzzCase, count)
	for i := range cases {
		fc := &fuzzCase{ID: fmt.Sprintf("fuzz/s%d/%04d", seed, i), Allow: f.tree(1 + f.rng.IntN(3))}
		if f.chance(0.15) {
			fc.Deny = f.tree(f.rng.IntN(2))
		}
		cases[i] = fc
	}
	return cases
}
