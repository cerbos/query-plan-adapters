package main

import (
	"fmt"
	"sort"
	"strings"
)

// The adapters that refuse an operator before translating keep the planner's operators as a list.
// It is generated from the goldens, so a PDP pin that brings a new operator changes every copy at
// once, and the golden drift check fails until the change is committed.

const generatedBy = "Code generated by conformance/generator from the operators in conformance/golden/. DO NOT EDIT."

// plannerOperatorFiles renders the operator list for each adapter that holds one, by path relative
// to the conformance directory.
func plannerOperatorFiles(recorded map[string][]*Golden) map[string][]byte {
	set := map[string]bool{}
	var walk func(v any)
	walk = func(v any) {
		switch t := v.(type) {
		case map[string]any:
			if op, ok := t["operator"].(string); ok {
				set[op] = true
			}
			for _, inner := range t {
				walk(inner)
			}
		case []any:
			for _, inner := range t {
				walk(inner)
			}
		}
	}
	for _, goldens := range recorded {
		for _, g := range goldens {
			walk(g.Plan)
		}
	}
	ops := make([]string, 0, len(set))
	for op := range set {
		ops = append(ops, op)
	}
	sort.Strings(ops)

	quoted := func(indent string, width int) string {
		var lines []string
		line := indent
		for i, op := range ops {
			item := fmt.Sprintf("%q", op)
			if i < len(ops)-1 {
				item += ","
			}
			if len(line)+len(item)+1 > width && line != indent {
				lines = append(lines, strings.TrimRight(line, " "))
				line = indent
			}
			line += item + " "
		}
		return strings.Join(append(lines, strings.TrimRight(line, " ")), "\n")
	}
	ts := fmt.Sprintf("// %s\n\nexport const PLANNER_OPERATORS: ReadonlySet<string> = new Set([\n%s\n]);\n", generatedBy, quoted("  ", 100))
	java := func(pkg string) []byte {
		return []byte(fmt.Sprintf("// %s\n\npackage %s;\n\nimport java.util.Set;\n\nfinal class PlannerOperators {\n    static final Set<String> ALL = Set.of(\n%s);\n\n    private PlannerOperators() {}\n}\n", generatedBy, pkg, quoted("            ", 100)))
	}
	kotlin := fmt.Sprintf("// %s\n\npackage dev.cerbos.queryplan.exposed\n\ninternal val PLANNER_OPERATORS: Set<String> = setOf(\n%s,\n)\n", generatedBy, quoted("    ", 100))
	ruby := fmt.Sprintf("# frozen_string_literal: true\n\n# %s\n\nmodule Cerbos\n  module MongoDB\n    module Plan\n      PLANNER_OPERATORS = %%w[\n%s\n      ].to_set.freeze\n    end\n  end\nend\n", generatedBy, wrapWords("        ", ops, 100))
	var py strings.Builder
	for _, op := range ops {
		py.WriteString(fmt.Sprintf("        %q,\n", op))
	}
	python := fmt.Sprintf("# %s\n\nPLANNER_OPERATORS: frozenset[str] = frozenset(\n    {\n%s    }\n)\n", generatedBy, py.String())
	return map[string][]byte{
		"../polars/src/cerbos_polars/_planner_operators.py":                                            []byte(python),
		"../prisma/src/planner-operators.ts":                                                           []byte(ts),
		"../mongoose/src/planner-operators.ts":                                                         []byte(ts),
		"../drizzle/src/planner-operators.ts":                                                          []byte(ts),
		"../jpa/src/main/java/dev/cerbos/queryplan/jpa/PlannerOperators.java":                          java("dev.cerbos.queryplan.jpa"),
		"../elasticsearch-java/src/main/java/dev/cerbos/queryplan/elasticsearch/PlannerOperators.java": java("dev.cerbos.queryplan.elasticsearch"),
		"../exposed/src/main/kotlin/dev/cerbos/queryplan/exposed/PlannerOperators.kt":                  []byte(kotlin),
		"../mongodb-ruby/lib/cerbos/mongodb/planner_operators.rb":                                      []byte(ruby),
	}
}

func wrapWords(indent string, words []string, width int) string {
	var lines []string
	line := indent
	for _, w := range words {
		if len(line)+len(w)+1 > width && line != indent {
			lines = append(lines, strings.TrimRight(line, " "))
			line = indent
		}
		line += w + " "
	}
	return strings.Join(append(lines, strings.TrimRight(line, " ")), "\n")
}
